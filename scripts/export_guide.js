// Write the query server's user guide (server/static/guide.js) as a standalone page,
// docs/user_guide.html, with the page's styles, the white theme, and the guide's images
// read from the checkout. Run from the repository root after the guide changes:
//
//   node scripts/export_guide.js
const fs = require("fs");
const vm = require("vm");

const STATIC = "aiprover_orchestration/server/static";
const FROM_DOCS = `../${STATIC}`;

const context = {};
vm.runInNewContext(`${fs.readFileSync(`${STATIC}/guide.js`, "utf8")}\nthis.html = GUIDE_HTML;`, context);
const html = context.html
  .replace(/data-themed-image="([^"]+)"/g, `src="${FROM_DOCS}/guide/white/$1"`)
  .replaceAll('"/static/', `"${FROM_DOCS}/`);
const style = fs.readFileSync(`${STATIC}/index.html`, "utf8").match(/<style>([\s\S]*?)<\/style>/)[1];

fs.writeFileSync("docs/user_guide.html", `<!doctype html>
<html lang="en" data-theme="white">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>AIProver user guide</title>
<!-- Generated by scripts/export_guide.js from ${STATIC}/guide.js; edit that file. -->
<link rel="stylesheet" href="${FROM_DOCS}/palette.css">
<style>${style}
.guide { margin: 32px auto; padding: 0 16px; }
</style>
</head>
<body class="reading">
<main class="guide">${html}</main>
</body>
</html>
`);
console.log("wrote docs/user_guide.html");
